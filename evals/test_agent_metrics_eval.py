    task_metric.measure(test_case)
    print(f"\n[TASK COMPLETION SCORE]: {task_metric.score}")
    print(f"[TASK COMPLETION REASON]: {task_metric.reason}")
    assert task_metric.is_successful()

    time.sleep(2)


